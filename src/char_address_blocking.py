# TEXT NORMALIZATION
# ============================================================

def normalize_unicode(text):
    """
    Unicode-safe normalization.

    IMPORTANT:
    We do NOT convert everything to ASCII.

    Hindi / Gujarati / Kannada etc. must remain searchable.
    """
    if pd.isna(text):
        return ""

    text = str(text)

    text = unicodedata.normalize("NFKC", text)
    text = text.casefold()

    # Convert punctuation/symbols to spaces,
    # while keeping Unicode letters/numbers.
    text = re.sub(r"[^\w\s]", " ", text, flags=re.UNICODE)

    text = re.sub(r"\s+", " ", text).strip()

    return text


def normalize_ascii(text):
    """
    Auxiliary ASCII normalization.

    This is ONLY an additional representation.
    It is NOT the primary representation.
    """
    if not text:
        return ""

    text = unicodedata.normalize("NFKD", text)

    text = text.encode(
        "ascii",
        "ignore"
    ).decode("ascii")

    text = text.casefold()

    text = re.sub(r"[^a-z0-9\s]", " ", text)

    text = re.sub(r"\s+", " ", text).strip()

    return text


def tokens(text):
    """
    Unicode-aware tokenization.
    """
    if not text:
        return []

    return re.findall(r"\w+", text, flags=re.UNICODE)


# ============================================================
# NAME NORMALIZATION
# ============================================================

LEGAL_SUFFIXES = {
    "private limited",
    "pvt ltd",
    "pvt",
    "limited",
    "ltd",
    "llc",
    "llp",
    "inc",
    "incorporated",
    "corporation",
    "corp",
    "company",
    "co",
    "plc",
    "gmbh",
}


def normalized_name(text):
    """
    Normalize business name while preserving Unicode.
    """
    text = normalize_unicode(text)

    if not text:
        return ""

    toks = tokens(text)

    # Remove legal suffixes token-wise.
    result = []
    i = 0

    while i < len(toks):

        # two-token suffix
        if i + 1 < len(toks):
            pair = toks[i] + " " + toks[i + 1]

            if pair in LEGAL_SUFFIXES:
                i += 2
                continue

        if toks[i] in LEGAL_SUFFIXES:
            i += 1
            continue

        result.append(toks[i])
        i += 1

    return " ".join(result)


def normalized_address(text):
    return normalize_unicode(text)


# ============================================================
# CHARACTER N-GRAMS
# ============================================================

def char_ngrams(text, n=CHAR_N):
    """
    Character n-grams with spaces included.

    Example:

        specialists

    becomes approximately:

        spe
        pec
        eci
        cia
        ial
        lis
        ist
        sts

    We keep spaces because word boundaries contain useful
    information.
    """
    if not text:
        return []

    # Add boundary markers.
    text = f" {text} "

    if len(text) < n:
        return [text]

    return [
        text[i:i+n]
        for i in range(len(text) - n + 1)
    ]


# ============================================================
# ADDRESS COMPONENT EXTRACTION
# ============================================================

def extract_numbers(address):
    """
    Extract numeric components.

    Examples:
        405 International Drive
        -> 405

        560001 Bangalore
        -> 560001
    """
    if not address:
        return []

    return re.findall(r"\d+[a-zA-Z]?", address)


def extract_address_tokens(address):
    """
    Extract useful address tokens.

    Very short generic tokens are ignored.
    """
    toks = tokens(address)

    result = []

    for t in toks:

        # Keep numbers.
        if any(ch.isdigit() for ch in t):
            result.append(t)
            continue

        # Ignore tiny tokens.
        if len(t) < 3:
            continue

        result.append(t)

    return result


