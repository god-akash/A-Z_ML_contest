def generate_candidates(info):

    country = info["country"]

    signal_candidates = {
        "exact_name": set(),
        "char_name": set(),
        "addr_token": set(),
        "addr_number": set(),
    }

    # ========================================================
    # SIGNAL 1: EXACT NAME
    # ========================================================

    if info["name"]:

        key = (
            country,
            info["name"]
        )

        signal_candidates["exact_name"].update(
            get_postings(
                exact_name_index,
                key,
                SIGNAL_CAP,
            )
        )

    # ========================================================
    # SIGNAL 2: CHARACTER NAME
    # ========================================================

    # Count votes for candidates based on shared
    # character n-grams.

    char_votes = Counter()

    for g in info["name_chars"]:

        key = (country, g)

        postings = get_postings(
            char_index,
            key,
            SIGNAL_CAP,
        )

        for eid in postings:
            char_votes[eid] += 1

    # Keep candidates with strongest ngram overlap.
    for eid, votes in char_votes.most_common(
        SIGNAL_CAP
    ):
        signal_candidates[
            "char_name"
        ].add(eid)

    # ========================================================
    # SIGNAL 3: ADDRESS TOKENS
    # ========================================================

    addr_votes = Counter()

    for tok in set(info["address_tokens"]):

        key = (
            country,
            tok
        )

        postings = get_postings(
            addr_token_index,
            key,
            SIGNAL_CAP,
        )

        for eid in postings:
            addr_votes[eid] += 1

    for eid, votes in addr_votes.most_common(
        SIGNAL_CAP
    ):
        signal_candidates[
            "addr_token"
        ].add(eid)

    # ========================================================
    # SIGNAL 4: ADDRESS NUMBERS
    # ========================================================

    number_candidates = set()

    for num in info["numbers"]:

        key = (
            country,
            num
        )

        number_candidates.update(
            get_postings(
                number_index,
                key,
                SIGNAL_CAP,
            )
        )

    signal_candidates[
        "addr_number"
    ] = number_candidates

    # ========================================================
    # UNION
    # ========================================================

    union = set()

    for vals in signal_candidates.values():
        union.update(vals)

    return signal_candidates, union


